using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Purview.Unions.SourceGenerator.Common;
using Purview.Unions.SourceGenerator.Models;

namespace Purview.Unions.SourceGenerator.Emit;

/// <summary>
/// Emits the C# 15 non-boxing custom-union shape for one union.
/// </summary>
static class UnionEmitter
{
	/// <summary>
	/// Emits the union source and adds it to the compilation.
	/// </summary>
	/// <param name="context">The source production context.</param>
	/// <param name="model">The union to emit.</param>
	/// <param name="generationContext">The operational generation context.</param>
	public static void Execute(SourceProductionContext context, UnionModel model, GeneratorContext generationContext)
	{
		var writer = generationContext.CreateCodeWriter();
		writer.AutoGeneratedHeader();

		if (!model.IsGlobalNamespace)
			writer.FileScopedNamespace(model.Namespace);

		EmitContainingTypes(writer, model, depth: 0);

		context.AddSource(model.HintName, SourceText.From(writer.ToString(), Encoding.UTF8));
	}

	static void EmitContainingTypes(CodeWriter writer, UnionModel model, int depth)
	{
		if (depth == model.ContainingTypes.Count)
		{
			EmitUnion(writer, model);

			return;
		}

		var containing = model.ContainingTypes[depth];
		TypeDeclarationOptions options = new(containing.Name, containing.Accessibility)
		{
			Kind = containing.Kind,
			IsPartial = true,
			IsReadOnly = containing.IsReadOnly,
			IsStatic = containing.IsStatic,
			IsSealed = false,
			IncludeGeneratedAttributes = false,
		};

		writer.Type(options, body => EmitContainingTypes(body, model, depth + 1));
	}

	static void EmitUnion(CodeWriter writer, UnionModel model)
	{
		var reference = CreateUnionReference(model);

		TypeDeclarationOptions options = new(model.Name, model.Accessibility)
		{
			Kind = model.Kind,
			IsPartial = true,
			IsReadOnly = model.IsReadOnly,
			IsStatic = false,
			IsSealed = false,
			GenericTypes = CreateGenericTypes(model),
			Interfaces = model.EmitMembers ? [new TypeReference(UnionsTypeLibrary.UnionInterface)] : [],
			Attributes = model.EmitUnionAttribute
				? [new AttributeDeclarationOptions(UnionsTypeLibrary.UnionAttribute)]
				: [],
		};

		writer.Type(options, body =>
		{
			if (!model.EmitMembers)
			{
				body.Comment(
					"The declaration is hand-written: its constructors and access members already exist, so only the compiler attribute is generated."
				);

				return;
			}

			EmitFields(body, model);
			EmitConstructors(body, model);
			EmitValue(body, model);
			EmitHasValue(body, model);
			EmitTryGetValue(body, model);
			EmitFactories(body, model, reference);
			EmitProviderFactories(body, model, reference);
		});
	}

	static void EmitFields(CodeWriter writer, UnionModel model)
	{
		foreach (var unionCase in model.Cases)
		{
			writer.Field(unionCase.FieldName, unionCase.StorageType, TypeDeclarationAccessibility.Private, options =>
				options with
				{
					IsReadOnly = true,
				}
			);
		}

		writer.Field(
			PropertyLibrary.TagFieldName,
			new TypeReference(new TypeIdentity(model.TagTypeName, null)),
			TypeDeclarationAccessibility.Private,
			options => options with { IsReadOnly = true }
		);
	}

	static void EmitConstructors(CodeWriter writer, UnionModel model)
	{
		if (model.CaseSource == UnionCaseSource.Provider)
		{
			EmitStorageConstructor(writer, model);

			return;
		}

		foreach (var unionCase in model.Cases)
		{
			writer.Constructor(
				model.Name,
				TypeDeclarationAccessibility.Public,
				options =>
					options with
					{
						Parameters =
						[
							new ParameterDeclarationOptions(
								PropertyLibrary.ValueParameterName,
								unionCase.ParameterType
							),
						],
					},
				body =>
				{
					if (unionCase.RequiresNullCheck)
						body.IfBlock($"{PropertyLibrary.ValueParameterName} is null", b => b.Return());

					for (var index = 0; index < model.Cases.Count; index++)
					{
						var other = model.Cases[index];
						body.Assignment(
							other.FieldName,
							index == unionCase.Tag - 1 ? ActiveValueExpression(unionCase) : "default"
						);
					}

					body.Assignment(
						PropertyLibrary.TagFieldName,
						unionCase.Tag.ToString(System.Globalization.CultureInfo.InvariantCulture)
					);
				}
			);
		}
	}

	/// <summary>
	/// Emits the single private constructor a union member provider's generated factory methods share.
	/// </summary>
	static void EmitStorageConstructor(CodeWriter writer, UnionModel model)
	{
		var parameters = ImmutableArray.CreateBuilder<ParameterDeclarationOptions>(model.Cases.Count + 1);

		foreach (var unionCase in model.Cases)
			parameters.Add(new ParameterDeclarationOptions(unionCase.FieldName, unionCase.StorageType));

		parameters.Add(
			new ParameterDeclarationOptions(
				PropertyLibrary.TagFieldName,
				new TypeReference(new TypeIdentity(model.TagTypeName, null))
			)
		);

		writer.Constructor(
			model.Name,
			TypeDeclarationAccessibility.Private,
			options => options with { Parameters = parameters.ToImmutable() },
			body =>
			{
				foreach (var unionCase in model.Cases)
					body.Assignment("this." + unionCase.FieldName, unionCase.FieldName);

				body.Assignment("this." + PropertyLibrary.TagFieldName, PropertyLibrary.TagFieldName);
			}
		);
	}

	static void EmitValue(CodeWriter writer, UnionModel model)
	{
		StringBuilder arms = new();
		foreach (var unionCase in model.Cases)
			arms.Append(unionCase.Tag).Append(" => ").Append(unionCase.FieldName).Append(", ");

		writer.Property(
			PropertyLibrary.ValueMemberName,
			TypeIdentity.Create<object>().MakeNullable(writer),
			TypeDeclarationAccessibility.Public,
			body => body.Return($"{PropertyLibrary.TagFieldName} switch {{ {arms}_ => null }}"),
			null
		);
	}

	static void EmitHasValue(CodeWriter writer, UnionModel model)
	{
		// HasValue is true iff Value is not null. A value-type case (including a nullable value type,
		// which is stored as its underlying type only when non-null) is never null once its tag is set,
		// so only reference and type-parameter cases need the per-case null test.
		StringBuilder arms = new();
		foreach (var unionCase in model.Cases)
		{
			arms.Append(unionCase.Tag)
				.Append(" => ")
				.Append(RequiresNullTest(unionCase) ? $"{unionCase.FieldName} is not null" : "true")
				.Append(", ");
		}

		writer.Property(
			PropertyLibrary.HasValueMemberName,
			TypeIdentity.Create<bool>().AsTypeReference(),
			TypeDeclarationAccessibility.Public,
			body => body.Return($"{PropertyLibrary.TagFieldName} switch {{ {arms}_ => false }}"),
			null
		);
	}

	static void EmitTryGetValue(CodeWriter writer, UnionModel model)
	{
		foreach (var unionCase in model.Cases)
		{
			writer.Method(
				PropertyLibrary.TryGetValueMemberName,
				TypeIdentity.Create<bool>().AsTypeReference(),
				TypeDeclarationAccessibility.Public,
				options =>
					options with
					{
						Parameters =
						[
							new ParameterDeclarationOptions(PropertyLibrary.ValueParameterName, unionCase.CaseType)
							{
								Modifier = ParameterModifier.Out,
							},
						],
					},
				body =>
				{
					body.Assignment(
						PropertyLibrary.ValueParameterName,
						RequiresNullTest(unionCase) ? unionCase.FieldName + "!" : unionCase.FieldName
					);

					var tag = PropertyLibrary.TagFieldName;
					body.Return(
						RequiresNullTest(unionCase)
							? $"{tag} == {unionCase.Tag} && {unionCase.FieldName} is not null"
							: $"{tag} == {unionCase.Tag}"
					);
				}
			);
		}
	}

	/// <summary>
	/// Emits the implementation parts of the union's own partial static factory signatures.
	/// </summary>
	static void EmitFactories(CodeWriter writer, UnionModel model, TypeReference reference)
	{
		if (model.CaseSource != UnionCaseSource.Factories)
			return;

		foreach (var factory in model.Factories)
		{
			writer.Method(
				factory.Name,
				reference,
				factory.Accessibility,
				options =>
					options with
					{
						IsStatic = true,
						IsPartial = true,
						Parameters =
						[
							new ParameterDeclarationOptions(PropertyLibrary.ValueParameterName, factory.ParameterType),
						],
					},
				body => body.Return($"new {reference.RenderFullName}({PropertyLibrary.ValueParameterName})")
			);
		}
	}

	/// <summary>
	/// Emits the case factories a union member provider's <c>Create</c> methods delegate to.
	/// </summary>
	/// <remarks>
	/// A union member provider's members are the only union members the compiler sees, so the union cannot
	/// expose public constructors. The provider's own one-line <c>Create</c> bodies call these methods,
	/// which build the value through the private storage constructor.
	/// </remarks>
	static void EmitProviderFactories(CodeWriter writer, UnionModel model, TypeReference reference)
	{
		if (model.CaseSource != UnionCaseSource.Provider)
			return;

		foreach (var unionCase in model.Cases)
		{
			writer.Method(
				PropertyLibrary.CreateCaseMethodPrefix
					+ (unionCase.Tag - 1).ToString(System.Globalization.CultureInfo.InvariantCulture),
				reference,
				TypeDeclarationAccessibility.Internal,
				options =>
					options with
					{
						IsStatic = true,
						Parameters =
						[
							new ParameterDeclarationOptions(
								PropertyLibrary.ValueParameterName,
								unionCase.ParameterType
							),
						],
					},
				body =>
				{
					if (unionCase.RequiresNullCheck)
						body.IfBlock($"{PropertyLibrary.ValueParameterName} is null", b => b.Return("default"));

					List<string> arguments = [with(model.Cases.Count + 1)];
					foreach (var other in model.Cases)
					{
						arguments.Add(other.Tag == unionCase.Tag ? ActiveValueExpression(unionCase) : "default");
					}

					arguments.Add(unionCase.Tag.ToString(System.Globalization.CultureInfo.InvariantCulture));

					body.Return($"new {reference.RenderFullName}({string.Join(", ", arguments)})");
				}
			);
		}
	}

	static string ActiveValueExpression(UnionCaseModel unionCase) =>
		unionCase.IsNullableValueType
			? $"{PropertyLibrary.ValueParameterName}.GetValueOrDefault()"
			: PropertyLibrary.ValueParameterName;

	static bool RequiresNullTest(UnionCaseModel unionCase) => unionCase.IsReferenceType || unionCase.IsTypeParameter;

	static TypeReference CreateUnionReference(UnionModel model)
	{
		if (model.TypeParameters.IsEmpty)
			return new TypeReference(model.UnionType);

		var arguments = new TypeReference[model.TypeParameters.Count];
		for (var index = 0; index < arguments.Length; index++)
			arguments[index] = new TypeReference(new TypeIdentity(model.TypeParameters[index].Name, null));

		return new TypeReference(model.UnionType.MakeGeneric(arguments));
	}

	static ImmutableArray<GenericTypeParameterOptions> CreateGenericTypes(UnionModel model)
	{
		if (model.TypeParameters.IsEmpty)
			return [];

		var builder = ImmutableArray.CreateBuilder<GenericTypeParameterOptions>(model.TypeParameters.Count);
		foreach (var parameter in model.TypeParameters)
		{
			builder.Add(
				new GenericTypeParameterOptions(parameter.Name)
				{
					Constraints = parameter.Constraints.AsImmutableArray(),
				}
			);
		}

		return builder.ToImmutable();
	}
}
