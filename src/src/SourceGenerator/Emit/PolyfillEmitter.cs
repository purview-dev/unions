using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Purview.Unions.SourceGenerator.Common;

namespace Purview.Unions.SourceGenerator.Emit;

/// <summary>
/// Emits the internal .NET 10 polyfills the compiler's union contract needs.
/// </summary>
/// <remarks>
/// <para>
/// <c>System.Runtime.CompilerServices.UnionAttribute</c> and <c>IUnion</c> are .NET 11 runtime types. A
/// project that targets <c>net10.0</c> compiles with the C# 15 compiler but references no such type, so
/// the generator supplies internal copies. The compiler recognises a union by the attribute's metadata
/// name, not by the assembly that defines it, so an internal polyfill in the consumer's own compilation is
/// enough.
/// </para>
/// <para>
/// The polyfills are emitted from a normal source output gated on
/// <c>compilation.GetTypeByMetadataName("System.Runtime.CompilerServices.UnionAttribute")</c> being null,
/// so a <c>net11.0</c> compilation — which has the real types — never receives a second definition. They
/// are emitted only when at least one union opted in, and never when the generator is disabled.
/// </para>
/// <para>
/// Both types are marked <c>[Embedded]</c> and <c>[CompilerGenerated]</c>, so they do not leak into the
/// public surface of the consuming assembly and are treated the way the compiler treats its own
/// synthesized attributes.
/// </para>
/// </remarks>
static class PolyfillEmitter
{
	/// <summary>
	/// The hint name of the generated polyfill file.
	/// </summary>
	public const string HintName = "UnionPolyfills.g.cs";

	/// <summary>
	/// Emits the polyfills into the compilation.
	/// </summary>
	/// <param name="context">The source production context.</param>
	/// <param name="generationContext">The operational generation context.</param>
	public static void Emit(SourceProductionContext context, GeneratorContext generationContext)
	{
		var writer = generationContext.CreateCodeWriter();
		writer.AutoGeneratedHeader();
		writer.FileScopedNamespace(PropertyLibrary.CompilerServicesNamespace);

		// The compiler recognises a union by this attribute's metadata name. Its shape mirrors the .NET 11
		// runtime type: sealed, applicable to classes and structs, and not repeatable.
		writer.AttributeClass(
			PropertyLibrary.UnionAttributeName,
			TypeDeclarationAccessibility.Internal,
			AttributeTargets.Class | AttributeTargets.Struct,
			_ => { },
			inherited: false,
			allowMultiple: false,
			configure: options => options with { IsSealed = true }
		);

		writer.Type(
			new TypeDeclarationOptions(PropertyLibrary.UnionInterfaceName, TypeDeclarationAccessibility.Internal)
			{
				Kind = TypeDeclarationKind.Interface,
				IsPartial = false,
				IncludeEmbeddedAttribute = true,
			},
			body =>
				body.Property(
					PropertyLibrary.ValueMemberName,
					TypeIdentity.Create<object>().MakeNullable(),
					TypeDeclarationAccessibility.Public,
					options => options with { HasGetter = true }
				)
		);

		context.AddSource(HintName, SourceText.From(writer.ToString(), Encoding.UTF8));
	}
}
